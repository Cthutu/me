#!/usr/bin/env python3
"""Generate local, dependency-free Unicode 16 grapheme tables and test vectors.

Download UCD inputs into _tmp/unicode before running. Runtime code uses no
Python or external library. Unicode data: https://www.unicode.org/license.txt
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / '_tmp/unicode'
PROPS = {'CR': 1, 'LF': 2, 'Control': 3, 'Extend': 4, 'ZWJ': 5,
         'Regional_Indicator': 6, 'Prepend': 7, 'SpacingMark': 8,
         'L': 9, 'V': 10, 'T': 11, 'LV': 12, 'LVT': 13}


def rows(name):
    for raw in (DATA / name).read_text().splitlines():
        parts = [p.strip() for p in raw.split('#')[0].split(';')]
        if len(parts) < 2:
            continue
        bounds = parts[0].split('..')
        yield int(bounds[0], 16), int(bounds[-1], 16), parts[1:]


def emit(name, entries):
    out = [f'pub {name} :: fn (r: u32) -> u8 {{']
    if name == 'grapheme_property':
        out += ['    on r >= 0xac00 && r <= 0xd7a3 => {',
                '        return on (r - 0xac00) % 28 == 0 { yes => 12 else => 13 }', '    }']
    out += ['    return on r {']
    merged = []
    for lo, hi, value in sorted(entries):
        if merged and merged[-1][1] + 1 == lo and merged[-1][2] == value:
            merged[-1] = (merged[-1][0], hi, value)
        else:
            merged.append((lo, hi, value))
    for lo, hi, value in merged:
        pattern = f'0x{lo:x}' if lo == hi else f'in [0x{lo:x}..=0x{hi:x}]'
        out.append(f'        {pattern} => {value}')
    out += ['        else => 0', '    }', '}', '']
    return '\n'.join(out)


out = ['-- Generated by build/generate_unicode.py; do not edit manually.',
       '-- Unicode 16.0.0, UAX #29 extended grapheme clusters.',
       '-- Unicode data licence: https://www.unicode.org/license.txt']
for name in ['GraphemeBreakProperty.txt', 'emoji-data.txt', 'DerivedCoreProperties.txt',
             'EastAsianWidth.txt', 'DerivedGeneralCategory.txt', 'PropList.txt']:
    out.append(f'-- {name} SHA-256: {hashlib.sha256((DATA/name).read_bytes()).hexdigest()}')
out += ['', emit('grapheme_property', [(lo, hi, PROPS[p[0]]) for lo, hi, p in rows('GraphemeBreakProperty.txt') if p[0] not in ('LV', 'LVT')]),
        emit('extended_pictographic', [(lo, hi, 1) for lo, hi, p in rows('emoji-data.txt') if p[0] == 'Extended_Pictographic']),
        emit('indic_property', [(lo, hi, {'Linker': 1, 'Consonant': 2, 'Extend': 3}[p[1]]) for lo, hi, p in rows('DerivedCoreProperties.txt') if p[0] == 'InCB']),
        emit('wide_property', [(lo, hi, 1) for lo, hi, p in rows('EastAsianWidth.txt') if p[0] in ('W', 'F')]),
        emit('zero_width_property', [(lo, hi, 1) for lo, hi, p in rows('DerivedGeneralCategory.txt') if p[0] in ('Mn', 'Me', 'Cf', 'Cc')]),
        emit('word_property', [(lo, hi, 1) for lo, hi, p in rows('DerivedGeneralCategory.txt') if p[0].startswith('L') or p[0] == 'Nd']),
        emit('whitespace_property', [(lo, hi, 1) for lo, hi, p in rows('PropList.txt') if p[0] == 'White_Space']),
        emit('emoji_presentation_property', [(lo, hi, 1) for lo, hi, p in rows('emoji-data.txt') if p[0] == 'Emoji_Presentation'])]
(ROOT/'src/unicode_data.n').write_text('\n'.join(out))
tests = ['-- Generated by build/generate_unicode.py; do not edit manually.',
         'test "Unicode 16 extended grapheme conformance" {']
count = 0
for raw in (DATA/'GraphemeBreakTest.txt').read_text().splitlines():
    parts = raw.split('#')[0].split()
    if not parts:
        continue
    text = bytearray()
    boundaries = []
    for part in parts:
        if part == '÷':
            boundaries.append(len(text))
        elif part != '×':
            text.extend(chr(int(part, 16)).encode())
    encoded = ''.join(f'\\x{b:02x}' for b in text)
    tests.append(f'    {{ text := "{encoded}"')
    for start, end in zip(boundaries, boundaries[1:]):
        tests.append(f'      assert next_character(text, {start}) == {end}, "Unicode case {count}"')
    tests.append('    }')
    count += 1
tests += ['}']
# Keep the generated vectors beside the segmentation implementation without
# overwriting its handwritten implementation or tests.
source_path = ROOT / 'src/characters.n'
source = source_path.read_text()
begin = '-- BEGIN GENERATED UNICODE CONFORMANCE'
end = '-- END GENERATED UNICODE CONFORMANCE'
if source.count(begin) != 1 or source.count(end) != 1:
    raise ValueError('Expected one Unicode conformance section in src/characters.n')
before, _, remaining = source.partition(begin)
_, found, after = remaining.partition(end)
if not found:
    raise ValueError('Unicode conformance section markers are out of order')
source_path.write_text(before + begin + '\n' + '\n'.join(tests) + '\n' + end + after)
print(f'Generated tables and {count} conformance vectors')
